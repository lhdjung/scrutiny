# Non-exported helper function that, by default, shows a message when the
# results of the main function (at the bottom) are returned:

explain_seq_test_ranking <- function(x, df_info) {
  if (!any(colnames(x) == "lead_lag")) {
    x$lead_lag <- NA
  }

  cons <- x$consistent[!is.na(x$consistent)]
  incons <- x$inconsistent[!is.na(x$inconsistent)]
  lead <- x$lead_lag[!is.na(x$lead_lag)]

  l_cons <- length(cons)
  l_incons <- length(incons)
  l_lead <- length(lead)

  if (l_lead > 0L) {
    if (l_lead > 1L) {
      if (all(lead > 0)) {
        lead_lag_info <- "lead"
      } else if (all(lead < 0)) {
        lead_lag_info <- "lag"
      } else {
        lead_lag_info <- "lead or lag"
      }
    } else {
      if (lead > 0) {
        lead_lag_info <- "leads"
      } else {
        lead_lag_info <- "lags"
      }
    }
  }

  lead <- abs(lead)

  if (l_cons == 0L) {
    cli::cli_inform(c(
      "Explanation: ",
      "i" = "All value sets of {df_info} are inconsistent. \n"
    ))
  } else if (l_incons == 0L) {
    cli::cli_inform(c(
      "Explanation: ",
      "i" = "All value sets of {df_info} are consistent. \n"
    ))
  } else {
    if (l_cons == 1L) {
      msg_cons <- glue::glue(
        "There is only 1 consistent value set. It's \\
                             in row number {cons} of {df_info}."
      )
      msg_lead <- glue::glue(
        "The consistent value set {lead_lag_info} the \\
                             first inconsistent one by {lead} places in \\
                             {df_info}. \n"
      )
    } else if (l_cons == 2L) {
      msg_cons <- glue::glue(
        "There are 2 consistent value sets, in rows \\
                             number {cons[1L]} and {cons[2L]} of {df_info}."
      )
      msg_lead <- glue::glue(
        "The consistent sets {lead_lag_info} the \\
                             inconsistent ones by {lead[1L]} and {lead[2L]} \\
                             places, respectively, in {df_info}. \n"
      )
    } else {
      msg_cons <- glue::glue(
        "There are {l_cons} consistent value sets, \\
                             starting with row number {cons[1L]} in \\
                             {df_info}."
      )
      msg_lead <- glue::glue(
        "The consistent sets {lead_lag_info} the \\
                             inconsistent ones by numbers of places from \\
                             {lead[1L]} to {lead[l_lead]} in {df_info}. \n"
      )
    }
    msg_incons <- "All other value sets are inconsistent."
    cli::cli_inform(c(
      "Explanation: ",
      "i" = msg_cons,
      "i" = msg_incons,
      "i" = msg_lead
    ))
  }
}


#' Rank sequence test results
#'
#' @description After testing a sequence from [`seq_endpoint_df()`] or
#'   [`seq_distance_df()`] with a mapper such as [`grim_map()`],
#'   `seq_test_ranking()` ranks the consistent and inconsistent results by
#'   their position in the sequence, and explains the result in a message.
#'
#' @param x Data frame returned by a mapper called on sequence output. A
#'   warning is issued if it is not.
#' @param explain Logical. Should the result be explained in a message?
#'   Default is `TRUE`.
#'
#' @return A tibble.
#'
#' @export
#'
#' @examples
#' seq_distance_df(.from = "0.00", n = 50) |>
#'   dplyr::mutate(x = as.numeric(x)) |>
#'   grim_map(digits_x = 2) |>
#'   seq_test_ranking()

seq_test_ranking <- function(x, explain = TRUE) {
  if (!any(colnames(x) == "consistency")) {
    cli::cli_abort(c(
      "Column `consistency` is missing.",
      "i" = "Only run `seq_test_ranking()` on the output of a \\
      mapping function, and only if that function was called to test a \\
      sequence generated by a function like one of scrutiny's `seq_*_df()` \\
      functions."
    ))
  }

  consistent <- which(x$consistency)
  inconsistent <- which(!x$consistency)

  l_cons <- length(consistent)
  l_incons <- length(inconsistent)

  greater_l <- max(l_cons, l_incons)
  lesser_l <- min(l_cons, l_incons)

  difference <- greater_l - lesser_l
  na_annex <- rep(NA, difference)

  if (l_cons > l_incons) {
    inconsistent <- append(inconsistent, na_annex)
  } else {
    consistent <- append(consistent, na_annex)
  }

  if (all(is.na(consistent))) {
    out <- tibble::tibble(consistent, inconsistent)
  } else {
    lead_lag <- inconsistent - consistent
    out <- tibble::tibble(consistent, inconsistent, lead_lag)
  }

  out <- out |>
    add_class("seq_test_ranking")

  # The mapper's test name is read from the `"scrutiny"` attribute, never
  # parsed out of a class name:
  name_test <- scrutiny_meta(x)$name_test
  if (is.null(name_test)) {
    df_info <- "the tested data frame"
    tested_with <- ""
  } else {
    df_info <- paste("the data frame tested with", name_test)
    tested_with <- paste(" with", name_test)
  }

  if (isTRUE(scrutiny_meta(x)$seq_test)) {
    if (explain) {
      explain_seq_test_ranking(out, df_info)
    }
    out
  } else {
    cli::cli_warn(c(
      "Is that really a sequence test?",
      "!" = "The data frame you tested{tested_with} wasn't created by \\
      `seq_endpoint_df()` or `seq_distance_df()`.",
      ">" = "Make sure you really tested a sequence. If you didn't, the \\
      results of `seq_test_ranking()` are probably not interpretable."
    ))
    out
  }
}
